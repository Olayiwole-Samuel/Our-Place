"use client";

import { useCallback, useEffect, useState } from "react";
import { Button } from "@/components/ui/Button";
import { PulseDots } from "@/components/ui/PulseDots";
import { useVisiblePolling } from "@/hooks/useVisiblePolling";
import { isRetryablePairingError, pairingErrorMessage } from "@/lib/couple/errors";
import { useCoupleStore } from "@/store/coupleStore";
import { toast } from "@/store/toastStore";

const PARTNER_CHECK_MS = 4000;

function formatExpiry(expiresAt) {
  const days = Math.max(1, Math.round((new Date(expiresAt).getTime() - Date.now()) / 86_400_000));
  return days === 1 ? "Expires in 1 day" : `Expires in ${days} days`;
}

/**
 * Shows the user's invite code (creating it on first open) and waits for their
 * partner to join. Pairing is detected by polling the server; the code itself is
 * generated by the database, never here.
 */
export function InviteCodePanel() {
  const invite = useCoupleStore((state) => state.invite);
  const createInvite = useCoupleStore((state) => state.createInvite);
  const refresh = useCoupleStore((state) => state.refresh);
  const [error, setError] = useState(null);
  const [canShare, setCanShare] = useState(false);

  const requestInvite = useCallback(async () => {
    setError(null);
    const result = await createInvite();
    if (!result.ok) setError(result.code);
  }, [createInvite]);

  useEffect(() => {
    setCanShare(typeof navigator !== "undefined" && typeof navigator.share === "function");
    if (!invite) requestInvite();
    // Only on open: an existing invite is reused, a missing one is created once.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // Watch for the partner joining (they pair from their own device).
  useVisiblePolling(refresh, PARTNER_CHECK_MS, Boolean(invite));

  async function copyCode() {
    try {
      await navigator.clipboard.writeText(invite.code);
      toast("Invite code copied.", "relationship");
    } catch {
      toast("Couldn't copy. Select the code and copy it manually.", "error");
    }
  }

  async function shareCode() {
    try {
      await navigator.share({
        title: "Our Place",
        text: `Join me in Our Place. My invite code is ${invite.code}`,
        url: window.location.origin,
      });
    } catch {
      // The user closed the share sheet — nothing to report.
    }
  }

  if (error && !invite) {
    return (
      <div role="alert" className="flex flex-col items-center gap-4 py-4 text-center">
        <p className="text-body text-text-secondary">{pairingErrorMessage(error)}</p>
        {isRetryablePairingError(error) && (
          <Button variant="secondary" onClick={requestInvite}>
            Try again
          </Button>
        )}
      </div>
    );
  }

  if (!invite) {
    return (
      <div role="status" className="flex flex-col items-center gap-4 py-6">
        <p className="micro-caps text-text-muted">Creating your invite</p>
        <PulseDots size="lg" />
      </div>
    );
  }

  return (
    <div className="flex flex-col items-center gap-5 text-center short:gap-3">
      <p className="micro-caps text-text-muted">Your invite code</p>

      {/* Visual cells for sighted users; screen readers get the code spelled out. */}
      <p className="sr-only">{`Your invite code is ${invite.code.split("").join(" ")}`}</p>
      <p aria-hidden="true" className="flex gap-1.5 select-all sm:gap-2 short:gap-1.5">
        {invite.code.split("").map((char, i) => (
          <span
            key={i}
            className="grid h-14 w-[clamp(2.25rem,11vw,2.75rem)] place-items-center rounded-[var(--radius-sm)] border border-[var(--border-strong)] bg-black-950 font-mono text-code text-white-soft short:h-12 short:w-10 sm:w-12"
          >
            {char}
          </span>
        ))}
      </p>

      <div className="flex flex-wrap items-center justify-center gap-2">
        <Button variant="relationship" onClick={copyCode}>
          <svg aria-hidden="true" width="16" height="16" viewBox="0 0 16 16" fill="none">
            <rect x="5" y="5" width="9" height="9" rx="2" stroke="currentColor" strokeWidth="1.5" />
            <path d="M11 5V3.5A1.5 1.5 0 0 0 9.5 2h-6A1.5 1.5 0 0 0 2 3.5v6A1.5 1.5 0 0 0 3.5 11H5" stroke="currentColor" strokeWidth="1.5" />
          </svg>
          Copy code
        </Button>
        {canShare && (
          <Button variant="secondary" onClick={shareCode}>
            Share
          </Button>
        )}
      </div>

      <div className="flex flex-col items-center gap-1.5">
        <p role="status" className="flex items-center gap-2 text-body text-text-secondary">
          <span aria-hidden="true" className="size-2 animate-pulse-live rounded-full bg-blue-400" />
          Waiting for your person…
        </p>
        <p className="text-caption text-text-muted">{formatExpiry(invite.expiresAt)} · Works once</p>
      </div>
    </div>
  );
}
